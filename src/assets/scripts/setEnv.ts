declare var require: any;
declare var process: any;
const { writeFile, existsSync, mkdirSync } = require('fs');

// need yargs to pass the command line arguments
const { argv } = require('yargs');

require('dotenv').config();

const environment = argv.environment;

//helper function to dynamically copy env variables into respective files if file dosen't exist, it'll make a new file on path
function writeFileUsingFS(targetPath, fileContent) {
  writeFile(targetPath, fileContent, function (err) {
    if (err) {
      console.log(err);
    }

    if (fileContent !== '') {
      console.log(`wrote variables to ${targetPath}`);
    }
  });
}

//path for the environment directory
const envDirectory = './src/environments';

//create a env directory if that directory dosen't exist
if (!existsSync(envDirectory)) {
  mkdirSync(envDirectory);
}

//create 'environment.ts' and 'environment.prod.ts' if that dosent exist
writeFileUsingFS('./src/environments/environment.development.ts', '');
writeFileUsingFS('./src/environments/environment.ts', '');

//check if argument of prod was given while built command
const isProduction = environment === 'prod';

//choose the correct file according to the configuration argument prod or not

const targetPath = isProduction
  ? './src/environments/environment.ts'
  : './src/environments/environment.development.ts';

const PRODUCTION_PROJECT_ID = 'devfest-siliguri';
const EMULATOR_PROJECT_ID = 'demo-gdg-siliguri';
const DEFAULT_EMULATOR_HOST = '127.0.0.1:8080';
const DATA_SOURCES = ['firestore', 'rtdb', 'fixture'];

const emulatorHost =
  process.env.FIRESTORE_EMULATOR_HOST || (isProduction ? '' : DEFAULT_EMULATOR_HOST);
const projectId =
  process.env.FIRESTORE_PROJECT_ID || (emulatorHost ? EMULATOR_PROJECT_ID : PRODUCTION_PROJECT_ID);
const firestoreBaseUrl = emulatorHost
  ? `http://${emulatorHost}/v1/projects/${projectId}/databases/(default)/documents`
  : `https://firestore.googleapis.com/v1/projects/${projectId}/databases/(default)/documents`;
const siteUrl = (process.env.SITE_URL || 'https://gdgsiliguri.com').replace(/\/+$/, '');
const dataSource = process.env.DATA_SOURCE || 'firestore';

if (!DATA_SOURCES.includes(dataSource)) {
  throw new Error(`DATA_SOURCE must be one of ${DATA_SOURCES.join(', ')}, got "${dataSource}"`);
}

//content to be compiled according to the target file
console.log('Getting env variable ------------------', environment);
console.log(`data source: ${dataSource}, firestore: ${firestoreBaseUrl}`);
const environmentFileContent = `
  //this file was autogenerated by dynamically running script file

  export const environment = {
      production: ${isProduction},
      apiKey: '${process.env.apiKey}',
      authDomain: '${process.env.authDomain}',
      databaseURL: '${process.env.databaseURL}',
      storageBucket: '${process.env.storageBucket}',
      messagingSenderId: '${process.env.messagingSenderId}',
      appId: '${process.env.appId}',
      apiBaseUrl: '${process.env.databaseURL}',
      projectId: '${projectId}',
      firestoreBaseUrl: '${firestoreBaseUrl}',
      dataSource: '${dataSource}' as 'firestore' | 'rtdb' | 'fixture',
      siteUrl: '${siteUrl}'
    }
`;

writeFileUsingFS(targetPath, environmentFileContent); //appending file data

